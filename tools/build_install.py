"""Builds templates/install.yaml from templates/src/install.src.yaml by placing
the reader and worker templates inside it (TemplateBody of their StackSets),
so each role is defined once. Comment lines are left out of the copies to
keep the StackSet bodies small (CloudFormation allows 51,200 bytes each).

    python tools/build_install.py
"""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "templates" / "src" / "install.src.yaml").read_text(encoding="utf-8")


def body(name: str, indent: str) -> str:
    text = (root / "templates" / name).read_text(encoding="utf-8")
    lines = [l for l in text.splitlines() if l.strip() and not l.lstrip().startswith("#")]
    out = "\n".join(lines)
    if len(out.encode("utf-8")) > 51200:
        raise SystemExit(f"{name} is {len(out.encode('utf-8'))} bytes: over the 51,200-byte StackSet template limit")
    # the first line goes where the placeholder is; the rest get its indent
    return ("\n" + indent).join(out.splitlines())


def place(text: str, marker: str, name: str) -> str:
    m = re.search(rf"^([ ]*){marker}$", text, re.MULTILINE)
    if not m:
        raise SystemExit(f"{marker} not found")
    return text[:m.start()] + m.group(1) + body(name, m.group(1)) + text[m.end():]


out = place(src, "__READER_TEMPLATE__", "reader.yaml")
out = place(out, "__WORKER_TEMPLATE__", "worker.yaml")
header = "# GENERATED by tools/build_install.py from templates/src/install.src.yaml. Don't edit this file.\n"
(root / "templates" / "install.yaml").write_text(header + out, encoding="utf-8")
print(f"templates/install.yaml: {len((header + out).encode('utf-8')):,} bytes")
